#!/usr/bin/env bash

# Setup colors
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

echo -e "${GREEN}Notki Installation & Update Script${NC}"
echo "====================================="

# Check for docker
if ! command -v docker &> /dev/null; then
    echo -e "${YELLOW}Docker is not installed. Please install Docker first.${NC}"
    exit 1
fi

# Determine if docker compose is a plugin or standalone
if docker compose version &> /dev/null; then
    DOCKER_COMPOSE="docker compose"
elif command -v docker-compose &> /dev/null; then
    DOCKER_COMPOSE="docker-compose"
else
    echo -e "${YELLOW}Docker Compose is not installed. Please install Docker Compose first.${NC}"
    exit 1
fi

IS_NEW_INSTALL=0

# Create .env if it doesn't exist
if [ ! -f .env ]; then
    echo -e "${GREEN}Creating new .env file...${NC}"
    IS_NEW_INSTALL=1

    # Generate random backup password
    BACKUP_PASSWORD=$(head -c 32 /dev/urandom | base64 | tr -d '+/' | head -c 24)
    SETUP_TOKEN=$(head -c 32 /dev/urandom | base64 | tr -d '+/' | head -c 24)

    cat <<ENV_EOF > .env
# Generated by install.sh
NOTKI_BACKUP_PASSWORD="${BACKUP_PASSWORD}"
NOTKI_SETUP_TOKEN="${SETUP_TOKEN}"
NOTKI_HTTP_PORT=8000
ENV_EOF

    echo -e "${YELLOW}IMPORTANT: Save this backup password! You will need it to restore backups.${NC}"
    echo -e "Backup Password: ${GREEN}${BACKUP_PASSWORD}${NC}"
    echo -e "${YELLOW}IMPORTANT: Save this setup token! You will need it to create the first admin account.${NC}"
    echo -e "Setup Token: ${GREEN}${SETUP_TOKEN}${NC}"
    echo ""
else
    echo -e "${GREEN}Existing .env file found. Proceeding with update...${NC}"
fi

echo -e "${GREEN}Building and starting Notki...${NC}"
$DOCKER_COMPOSE up -d --build

echo -e "${GREEN}Cleaning up old Docker images...${NC}"
docker image prune -f

if [ $IS_NEW_INSTALL -eq 1 ]; then
    echo -e "${GREEN}Installation complete!${NC}"
    echo -e "Go to ${YELLOW}http://localhost:8000/setup${NC} to create your admin account."
    echo -e "Use the Setup Token displayed above."
else
    echo -e "${GREEN}Update complete!${NC}"
fi
